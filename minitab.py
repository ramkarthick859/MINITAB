import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats

st.set_page_config(
    page_title="PyTab - Statistical Analysis App",
    page_icon="📊",
    layout="wide"
)

st.title("📊 PyTab: Minitab-Style Statistical Analysis")

# Sidebar - File Upload
uploaded_file = st.sidebar.file_uploader("Upload CSV or Excel file", type=["csv", "xlsx"])

if uploaded_file is not None:
    try:
        if uploaded_file.name.endswith('.csv'):
            df = pd.read_csv(uploaded_file)
        else:
            df = pd.read_excel(uploaded_file)

        st.sidebar.success("File successfully loaded!")
    except Exception as e:
        st.sidebar.error(f"Error loading file: {e}")
        st.stop()

    menu = st.sidebar.radio(
        "Select Module",
        [
            "Data Overview",
            "Descriptive Statistics",
            "Control Charts (I-MR)",
            "Process Capability (Cp / Cpk)",
            "Hypothesis Testing"
        ]
    )

    # ---------------------------------------------------------
    # Module 1: Data Overview
    # ---------------------------------------------------------
    if menu == "Data Overview":
        st.header("Dataset Overview")
        col1, col2 = st.columns(2)
        with col1:
            st.metric("Total Rows", df.shape[0])
        with col2:
            st.metric("Total Columns", df.shape[1])

        st.subheader("Data Preview")
        st.dataframe(df.head(10), use_container_width=True)

        st.subheader("Column Data Types & Missing Values")
        info_df = pd.DataFrame({
            "Data Type": df.dtypes.astype(str),
            "Missing Values": df.isnull().sum()
        })
        st.dataframe(info_df, use_container_width=True)

    # ---------------------------------------------------------
    # Module 2: Descriptive Statistics
    # ---------------------------------------------------------
    elif menu == "Descriptive Statistics":
        st.header("Descriptive Statistics")
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()

        if not numeric_cols:
            st.warning("No numeric columns found in the dataset.")
        else:
            selected_col = st.selectbox("Select Numeric Column", numeric_cols)
            data = df[selected_col].dropna()

            col1, col2 = st.columns([1, 2])

            with col1:
                st.subheader("Summary Metrics")
                stats_df = pd.DataFrame({
                    "Metric": [
                        "Count", "Mean", "Std Deviation", "Variance",
                        "Minimum", "1st Quartile (Q1)", "Median (Q2)",
                        "3rd Quartile (Q3)", "Maximum", "Skewness", "Kurtosis"
                    ],
                    "Value": [
                        len(data),
                        data.mean(),
                        data.std(),
                        data.var(),
                        data.min(),
                        data.quantile(0.25),
                        data.median(),
                        data.quantile(0.75),
                        data.max(),
                        data.skew(),
                        data.kurtosis()
                    ]
                })
                st.dataframe(stats_df, hide_index=True, use_container_width=True)

            with col2:
                st.subheader("Visualizations")
                fig, (ax_hist, ax_box) = plt.subplots(1, 2, figsize=(10, 4))

                # Histogram + KDE
                sns.histplot(data, kde=True, ax=ax_hist, color="steelblue")
                ax_hist.set_title(f"Histogram of {selected_col}")

                # Boxplot
                sns.boxplot(y=data, ax=ax_box, color="mediumseagreen")
                ax_box.set_title(f"Boxplot of {selected_col}")

                st.pyplot(fig)

    # ---------------------------------------------------------
    # Module 3: Control Charts (I-MR)
    # ---------------------------------------------------------
    elif menu == "Control Charts (I-MR)":
        st.header("Statistical Process Control: I-MR Chart")
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()

        if not numeric_cols:
            st.warning("No numeric columns found in the dataset.")
        else:
            selected_col = st.selectbox("Select Variable for Control Chart", numeric_cols)
            data = df[selected_col].dropna().reset_index(drop=True)

            # Individuals Chart Calculations
            x_bar = data.mean()
            mr = np.abs(data.diff())
            mr_bar = mr.mean()

            ucl_i = x_bar + 2.66 * mr_bar
            lcl_i = x_bar - 2.66 * mr_bar
            ucl_mr = 3.267 * mr_bar

            fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=True)

            # Individual Plot
            ax1.plot(data, marker='o', color='navy', linewidth=1)
            ax1.axhline(x_bar, color='green', linestyle='--', label=f'Mean = {x_bar:.2f}')
            ax1.axhline(ucl_i, color='red', linestyle='--', label=f'UCL = {ucl_i:.2f}')
            ax1.axhline(lcl_i, color='red', linestyle='--', label=f'LCL = {lcl_i:.2f}')
            ax1.set_title(f"Individual (I) Chart for {selected_col}")
            ax1.legend(loc="upper right")

            # Moving Range Plot
            ax2.plot(mr, marker='o', color='darkorange', linewidth=1)
            ax2.axhline(mr_bar, color='green', linestyle='--', label=f'MR Mean = {mr_bar:.2f}')
            ax2.axhline(ucl_mr, color='red', linestyle='--', label=f'UCL = {ucl_mr:.2f}')
            ax2.axhline(0, color='red', linestyle='--', label='LCL = 0.00')
            ax2.set_title("Moving Range (MR) Chart")
            ax2.legend(loc="upper right")

            st.pyplot(fig)

    # ---------------------------------------------------------
    # Module 4: Process Capability (Cp / Cpk)
    # ---------------------------------------------------------
    elif menu == "Process Capability (Cp / Cpk)":
        st.header("Process Capability Analysis")
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()

        if not numeric_cols:
            st.warning("No numeric columns found in the dataset.")
        else:
            selected_col = st.selectbox("Select Measured Variable", numeric_cols)
            data = df[selected_col].dropna()

            col_input1, col_input2 = st.columns(2)
            with col_input1:
                lsl = st.number_input("Lower Specification Limit (LSL)", value=float(data.min()))
            with col_input2:
                usl = st.number_input("Upper Specification Limit (USL)", value=float(data.max()))

            mean = data.mean()
            std = data.std()

            if std > 0 and usl > lsl:
                cp = (usl - lsl) / (6 * std)
                cpu = (usl - mean) / (3 * std)
                cpl = (mean - lsl) / (3 * std)
                cpk = min(cpu, cpl)

                m1, m2, m3, m4 = st.columns(4)
                m1.metric("Mean ($\mu$)", f"{mean:.4f}")
                m2.metric("Std Dev ($\sigma$)", f"{std:.4f}")
                m3.metric("Capability ($C_p$)", f"{cp:.4f}")
                m4.metric("Capability Index ($C_{pk}$)", f"{cpk:.4f}")

                fig, ax = plt.subplots(figsize=(8, 4))
                sns.histplot(data, kde=True, ax=ax, color='purple', stat="density")
                ax.axvline(lsl, color='red', linestyle='--', linewidth=2, label=f'LSL ({lsl:.2f})')
                ax.axvline(usl, color='red', linestyle='--', linewidth=2, label=f'USL ({usl:.2f})')
                ax.axvline(mean, color='green', linestyle='-', linewidth=2, label=f'Mean ({mean:.2f})')
                ax.set_title(f"Capability Histogram for {selected_col}")
                ax.legend()

                st.pyplot(fig)
            else:
                st.error("USL must be strictly greater than LSL, and standard deviation must be non-zero.")

    # ---------------------------------------------------------
    # Module 5: Hypothesis Testing
    # ---------------------------------------------------------
    elif menu == "Hypothesis Testing":
        st.header("Hypothesis Testing")
        test_type = st.selectbox(
            "Select Test Type",
            ["1-Sample t-Test", "2-Sample Independent t-Test", "One-Way ANOVA"]
        )

        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        cat_cols = df.select_dtypes(include=['object', 'category']).columns.tolist()

        if test_type == "1-Sample t-Test" and numeric_cols:
            col = st.selectbox("Select Variable", numeric_cols)
            target_mean = st.number_input("Hypothesized Mean ($\mu_0$)", value=0.0)

            if st.button("Run Test"):
                t_stat, p_val = stats.ttest_1samp(df[col].dropna(), target_mean)
                st.write(f"**t-Statistic:** `{t_stat:.4f}`")
                st.write(f"**p-Value:** `{p_val:.4e}`")

                if p_val < 0.05:
                    st.error("Reject $H_0$: There is a statistically significant difference from the target mean ($\alpha=0.05$).")
                else:
                    st.success("Fail to reject $H_0$: No statistically significant difference detected ($\alpha=0.05$).")

        elif test_type == "2-Sample Independent t-Test" and len(numeric_cols) >= 2:
            col1 = st.selectbox("Select Sample 1 (Numeric)", numeric_cols, index=0)
            col2 = st.selectbox("Select Sample 2 (Numeric)", numeric_cols, index=1)

            if st.button("Run Test"):
                t_stat, p_val = stats.ttest_ind(df[col1].dropna(), df[col2].dropna())
                st.write(f"**t-Statistic:** `{t_stat:.4f}`")
                st.write(f"**p-Value:** `{p_val:.4e}`")

                if p_val < 0.05:
                    st.error("Reject $H_0$: Significant difference between the two sample means ($\alpha=0.05$).")
                else:
                    st.success("Fail to reject $H_0$: No significant difference detected ($\alpha=0.05$).")

        elif test_type == "One-Way ANOVA":
            if numeric_cols and cat_cols:
                num_col = st.selectbox("Select Continuous Response Variable", numeric_cols)
                cat_col = st.selectbox("Select Categorical Factor Variable", cat_cols)

                if st.button("Run ANOVA"):
                    groups = [group[num_col].dropna() for _, group in df.groupby(cat_col)]
                    f_stat, p_val = stats.f_oneway(*groups)
                    st.write(f"**F-Statistic:** `{f_stat:.4f}`")
                    st.write(f"**p-Value:** `{p_val:.4e}`")

                    if p_val < 0.05:
                        st.error("Reject $H_0$: At least one group mean significantly differs ($\alpha=0.05$).")
                    else:
                        st.success("Fail to reject $H_0$: No significant difference across groups ($\alpha=0.05$).")
            else:
                st.info("ANOVA requires at least one numerical variable and one categorical variable.")

else:
    st.info("👈 Upload a CSV or Excel file from the sidebar to begin analysis.")